class SchemaField extends code.Field {
  SchemaField(
      DomainClassMeta domainClass, MapConverterLibraryAssetIdFactory idFactory)
      : super('schema',
            type: _type(),
            value: _toMapExpression(domainClass, idFactory),
            modifier: code.Modifier.final$);

  static code.Type _type() {
    return code.Type.ofMap(
        keyType: code.Type.ofString(), valueType: code.Type.ofDynamic());
  }

  static code.Expression _toMapExpression(DomainClassMeta domainClass,
          MapConverterLibraryAssetIdFactory idFactory) =>
      code.Expression([
        code.KeyWord.const$,
        code.Space(),
        code.Expression.ofMap({
          code.Expression.ofString('className'):
              code.Expression.ofString(domainClass.classElement.name!),
          code.Expression.ofString('classDescription'):
              code.Expression.ofString(
                  domainClass.classElement.documentationComment ?? ''),
          code.Expression.ofString('classLibraryUri'): code.Expression.ofString(
              domainClass.classElement.library.uri.toString()),
          code.Expression.ofString('mapperClassName'): code.Expression.ofString(
              '${domainClass.classElement.name}Mapper'),
          code.Expression.ofString('mapperClassLibraryUri'):
              code.Expression.ofString(idFactory
                  .createOutputUriForType(domainClass.classElement.thisType)),
          code.Expression.ofString('fields'):
              _toFieldsExpression(domainClass.fields)
        })
      ]);

  static code.Expression _toFieldsExpression(List<FieldMetadata> fields) =>
      code.Expression.ofList(fields.map(_toFieldMapExpression).toList());

  static code.Expression _toFieldMapExpression(FieldMetadata field) =>
      code.Expression.ofMap({
        code.Expression.ofString('name'):
            code.Expression.ofString(field.element.name!),
        code.Expression.ofString('mapKey'):
            code.Expression.ofString(field.alias ?? field.element.name!),
        code.Expression.ofString('description'):
            code.Expression.ofString(field.element.documentationComment ?? ''),
        code.Expression.ofString('presence'): code.Expression.ofString(
            field.element.type.nullabilitySuffix == NullabilitySuffix.question
                ? 'optional'
                : 'required'),
        code.Expression.ofString('type'):
            code.Expression.ofString(field.element.type.getDisplayString()),
        code.Expression.ofString('typeLibraryUri'): code.Expression.ofString(
            field.element.type.element?.library?.uri.toString() ?? ''),
      });
}

code.Type createType(Element element, bool nullable) => code.Type(
      element.displayName,
      libraryUri: createLibraryUri(element),
      nullable: nullable,
    );

String? createLibraryUri(Element element) {
  String libraryUri = element.library?.uri.toString() ?? '';
  if (libraryUri == 'dart:core') {
    return null;
  }
  if (libraryUri.startsWith('package:')) {
    return libraryUri;
  }
  return createRelativeLibraryUri(libraryUri);
}

String createRelativeLibraryUri(String libraryUri) {
  var numberOfSlashes = '/'.allMatches(libraryUri).length;
  var foldersUpToRoot = numberOfSlashes - 1;
  int indexFirstSlash = libraryUri.indexOf('/');
  if (indexFirstSlash == -1) {
    return libraryUri;
  }
  return '${'../' * foldersUpToRoot}${libraryUri.substring(indexFirstSlash + 1)}';
}
